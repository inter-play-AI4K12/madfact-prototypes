import assert from 'node:assert/strict';
import {FloorPlacement} from '../Assets/FloorPlacement.ts';
const eye={x:0,y:170,z:0}, floor={x:0,y:0,z:-130}, up={x:0,y:1,z:0};
const gate=new FloorPlacement();
const first=gate.begin();
assert.equal(gate.confirm(0),null,'cannot pin without a surface');
assert.equal(gate.accept(first,floor,{x:0,y:0,z:1},eye,0),false,'reject walls');
assert.equal(gate.accept(first,floor,{x:0,y:-1,z:0},eye,0),false,'reject downward surfaces');
assert.equal(gate.accept(first,{x:0,y:130,z:-100},up,eye,0),false,'reject surfaces near eye height');
assert.equal(gate.accept(first,{x:0,y:0,z:-500},up,eye,0),false,'reject out-of-range surfaces');
assert.equal(gate.accept(first,{x:NaN,y:0,z:0},up,eye,0),false,'reject invalid geometry');
assert.equal(gate.accept(first,floor,up,eye,1),true);
assert.equal(gate.ready(1.4),true);assert.equal(gate.ready(1.51),false,'stale preview cannot be pinned');
assert.equal(gate.confirm(1.51),null);
assert.equal(gate.accept(first,floor,up,eye,2),true);
assert.deepEqual(gate.confirm(2.1),floor);assert.equal(gate.scanning,false);
assert.equal(gate.accept(first,{x:10,y:0,z:-150},up,eye,2.2),false,'late callbacks cannot move pinned exhibit');
const second=gate.begin();assert.equal(gate.candidate,null);
assert.equal(gate.accept(first,floor,up,eye,3),false,'old session results cannot position a new preview');
assert.equal(gate.accept(second,floor,up,eye,3),true);
assert.equal(gate.accept(second,null,null,eye,3.1),false);assert.equal(gate.ready(3.1),false,'lost surface disables confirmation');
console.log('PASS: floor geometry filters, no-hit gating, freshness, confirmation, pin immobility, and reposition callback isolation.');
